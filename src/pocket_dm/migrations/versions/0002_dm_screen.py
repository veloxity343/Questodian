def _move_session_encounters() -> None:
    conn = op.get_bind()
    now = datetime.now(UTC).isoformat(timespec="seconds")
    rows = conn.execute(sa.text("SELECT id, campaign_id, number, title, encounter FROM sessions")).fetchall()
    for sid, cid, number, title, raw in rows:
        enc = json.loads(raw) if isinstance(raw, str) else (raw or {})
        if not enc.get("combatants"):
            continue
        conn.execute(
            sa.text(
                "INSERT INTO encounters (id, created, updated, campaign_id, session_id, scene_id, name, round, turn,"
                " active, combatants, party_size, party_level, log, notes) VALUES (:id, :now, :now, :cid, :sid, NULL,"
                " :name, :round, :turn, :active, :combatants, :size, 1, '[]', '')"
            ),
            {
                "id": uuid.uuid4().hex[:12], "now": now, "cid": cid, "sid": sid,
                "name": f"Session {number}: {title}", "round": enc.get("round", 0), "turn": enc.get("turn", 0),
                "active": bool(enc.get("active")), "combatants": json.dumps(enc["combatants"]),
                "size": max(1, sum(1 for c in enc["combatants"] if c.get("kind") == "pc")) or 4,
            },
        )


